;==========================================================================
;  Placed target output (deleted at step 65.4)
;==========================================================================
;
;  Nucleus is its own linker, and this module is where it lays out a
;  complete program image at final addresses: the entry jump, the Nucleus
;  runtime's helper image, the startup code, the read-only constants, the
;  generated code and, for a loaded image, the initialised data. The
;  output adapter behind the PUB_ entries owns object framing, service
;  destinations, image fill and the CRC. In BASIE.COM those entries are the
;  stubs in SHELL.ASM, which discard what they are given, so the bytes this
;  module places go nowhere. Basie emits relocatable blobs that BLINK
;  places, and blob output replaces the whole module at step 65.4. It
;  therefore has only this header and Nucleus's own comments, not the
;  line-by-line commentary of the other modules.
;
;  TG_OPEN validates the target descriptor that the shell passes in IX
;  (SH_DESC; layout TG_D* in TGTWORK.ASM): the runtime identity must be
;  RT_IDENT and both regions must fit in memory. TG_CLASS then classifies
;  the writable region against the image, loaded (TG_LMODE zero) when it
;  lies inside the image and ROM when the two are disjoint, and refuses a
;  partial overlap. TG_OPEN sizes the startup (TG_ILEN) and the read-only
;  prefix, checks that at least one code byte fits and falls into TG_BEGIN,
;  which opens the output (PUB_OPEN), emits the entry JP, has PUB_RT supply
;  the runtime helpers, builds the link context (TG_SETUP) and emits the
;  startup (TG_BOOT): an optional switch to the target's own stack, for a
;  ROM image the copy of the runtime's vectors and state and the
;  initialised data into RAM, the bss clear, the call or jump to main and
;  the terminal dispatch through runtime vectors 6, 7 and 8. Code generation follows. TG_SHUT appends the initialised data of
;  a loaded image, fills the map record at TG_MAP and commits the output
;  through PUB_FLAT and PUB_CMT.
;
;  The multi-bank paths (TG_OPENB, TG_PICK, TG_SAVE, TG_SHUTB) are chosen
;  at run time by the descriptor's bank count. BASIE.COM's descriptor names
;  one bank, so they never run there.
;
;  Principal entries:
;    TG_OPEN   validate the descriptor at IX, lay out the image, begin output
;    TG_SHUT   finish placed output: data image, map, commit
;    TG_PICK   select the bank that receives generated bytes
;    TG_SAVE   save the selected bank's output cursor and capacity
;    TG_RAM    append the runtime's initialised vectors and state
;    TG_ABORT  abandon an open output generation; carry set
;    TG_FAIL   turn an output failure into a diagnostic (DG_OUT)
;    TG_FULL   raise DG_IMAGE when the image overflows
;    TG_DENY   raise DG_CFG for a descriptor the compiler cannot serve
;    TG_VAR    address of runtime-state offset DE in the target
;    EM_HELP   emit CALL to the runtime helper at offset DE
;    EM_CALLV  emit CALL through runtime vector A
;    EM_JUMPV  emit JP through runtime vector A
;
;  It owns the TG_ fields of TGTWORK.ASM: the layout block at TG_LBASE,
;  the link context at TG_CBASE and the map at TG_MAP, all of which reuse
;  the LL(1) parser's stack once parsing is over.

; Emit entry opcode A followed by one retained zero-word fixup operand.
;@ROUTINE IN A OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,DE,HL
TG_STUB:
    CALL EM_BYTE
    LD   HL,(EM_PTR)
    LD   (EM_DFIX),HL
    LD   HL,0
    JP   EM_WORD

; Emit one terminal-state byte comparison. DE selects the runtime-state byte
; and C supplies the expected value.
;@ROUTINE IN C,DE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,DE,HL
TG_TEST:
    PUSH BC
    CALL TG_VAR
    LD   A,$3A                     ; LD A,(nn)
    CALL EM_OPW
    POP  BC
    LD   A,$FE                     ; CP n
    CALL EM_OPB
    LD   HL,GT_ANDIF+3
    JP   EM_PAIR

; IX points at the stable compact descriptor supplied by the adapter.
;@ROUTINE IN IX OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_OPEN:
    LD   A,TG_OFF
    LD   (TG_OBANK),A
    LD   L,(IX+TG_DRT)
    LD   H,(IX+TG_DRT+1)
    LD   DE,RT_IDENT
    OR   A
    SBC  HL,DE
    JP   NZ,TG_DENY
    LD   A,(IX+TG_DFLAG)
    CP   TG_FSP+1
    JP   NC,TG_DENY
    LD   (TG_SMODE),A
    LD   L,(IX+TG_DIMG)
    LD   H,(IX+TG_DIMG+1)
    LD   (TG_IMAGE),HL
    LD   E,(IX+TG_DICAP)
    LD   D,(IX+TG_DICAP+1)
    LD   (TG_ICAP),DE
    CALL TG_CHECK
    LD   L,(IX+TG_DRAM)
    LD   H,(IX+TG_DRAM+1)
    LD   (TG_RW),HL
    LD   E,(IX+TG_DRCAP)
    LD   D,(IX+TG_DRCAP+1)
    LD   (TG_RCAP),DE
    CALL TG_CHECK
    CALL TG_CLASS
; Determine the exact startup extent and validate the optional
; established stack before the adapter opens a generation.
    LD   HL,26                     ; JP/CALL main plus terminal dispatch
    LD   A,(TG_LMODE)
    OR   A
    JR   Z,.BSS
    LD   DE,11                     ; LD HL/DE/BC plus LDIR
    ADD  HL,DE
.BSS:
    LD   DE,(PR_BSS)
    LD   A,D
    OR   E
    JR   Z,.STACK
    LD   DE,9                      ; LD HL/BC plus CALL InitializeBss
    ADD  HL,DE
.STACK:
    LD   A,(TG_SMODE)
    OR   A
    JR   Z,.SIZED
    LD   DE,13                     ; save/select SP plus terminal restore
    ADD  HL,DE
    PUSH HL
    CALL TG_SIZE
    JR   C,.STACKBAD
    LD   DE,(PR_BSS)
    ADD  HL,DE
    JR   C,.STACKBAD
    LD   DE,TG_STACK+2
    ADD  HL,DE
    JR   C,.STACKBAD
    LD   DE,(TG_RCAP)
    OR   A
    SBC  HL,DE
    JR   C,.STACKOK
    JR   Z,.STACKOK
.STACKBAD:
    POP  HL
    JR   TG_FULL
.STACKOK:
    POP  HL
.SIZED:
    LD   (TG_ILEN),HL
    LD   A,(TG_BCNT)
    CP   1
    JP   NZ,TG_OPENB
    LD   HL,(AG_ROLEN)
    LD   A,(TG_LMODE)
    OR   A
    JR   Z,.ROSIZED
    LD   DE,(AG_DLEN)
    ADD  HL,DE
    JR   C,.FULL
    LD   DE,RT_VLEN+RT_SLEN
    ADD  HL,DE
    JR   C,.FULL
.ROSIZED:
    LD   (TG_ROLEN),HL
    LD   DE,RT_SIZE+3
    ADD  HL,DE
    JR   C,.FULL
    LD   DE,(TG_ILEN)
    ADD  HL,DE
    JR   C,.FULL
    EX   DE,HL                     ; DE is fixed prefix length
    LD   HL,(TG_ICAP)
    OR   A
    SBC  HL,DE
    JR   C,.FULL
    LD   A,H
    OR   L
    JR   Z,.FULL                   ; at least one code byte is required
    LD   (EM_LIM),HL               ; remaining code capacity after prefix
    LD   HL,(TG_IMAGE)
    ADD  HL,DE
    JR   C,.FULL
    LD   (TG_CODE),HL
    LD   HL,(EM_LIM)
    LD   (TG_CCAP),HL
    LD   A,(TG_LMODE)
    OR   A
    JR   NZ,TG_BEGIN
    LD   DE,(TG_CODE)
    LD   HL,(TG_RW)
    OR   A
    SBC  HL,DE
    JR   C,.FULL
    JR   Z,.FULL
    LD   (TG_CCAP),HL
    JR   TG_BEGIN
.FULL:
TG_FULL:
    CALL DG_RAISE
    DB   DG_IMAGE
TG_BEGIN:

    LD   IX,(TG_DESC)
    CALL PUB_OPEN
    JP   C,TG_FAIL
    XOR  A
    LD   (TG_OBANK),A
    LD   HL,(TG_IMAGE)
    LD   (EM_PTR),HL
    LD   HL,(TG_ICAP)
    LD   (EM_LIM),HL
    LD   A,$C3
    CALL TG_STUB

    LD   HL,(EM_PTR)
    LD   (TG_RT),HL
    LD   DE,RT_SIZE
    ADD  HL,DE
    JR   C,TG_FULL
    LD   DE,(TG_ILEN)
    ADD  HL,DE
    JR   C,TG_FULL
    LD   (TG_RO),HL
    CALL TG_SETUP
    LD   HL,(TG_RT)
    XOR  A
    CALL TG_LINK
    JP   TG_BOOT

; Address one retained output-bank cursor and exact remaining-capacity word.
;@ROUTINE IN A OUT A,HL,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,D,DE
TG_CELL:
    LD   L,A
    LD   H,0
    ADD  HL,HL
    ADD  HL,HL
    LD   DE,TG_BTAB
    ADD  HL,DE
    OR   A
    RET

;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,D,DE,HL
TG_SAVE:
    LD   A,(TG_OBANK)
    CP   TG_OFF
    RET  Z
    CALL TG_CELL
    LD   DE,(EM_PTR)
    LD   (HL),E
    INC  HL
    LD   (HL),D
    INC  HL
    LD   DE,(EM_LIM)
    LD   (HL),E
    INC  HL
    LD   (HL),D
    OR   A
    RET

; Select the bank that receives subsequent generated bytes and derive the
; bank-local aggregate-constant bounds carried by generated region checks.
;@ROUTINE IN A OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,D,DE,HL
TG_PICK:
    LD   C,A
    LD   A,(TG_BCNT)
    DEC  A
    CP   C
    JP   C,TG_DENY
    LD   A,(TG_OBANK)
    CP   C
    RET  Z
    CALL TG_SAVE
    LD   A,C
    LD   (TG_OBANK),A
    CALL TG_CELL
    LD   E,(HL)
    INC  HL
    LD   D,(HL)
    LD   (EM_PTR),DE
    INC  HL
    LD   E,(HL)
    INC  HL
    LD   D,(HL)
    LD   (EM_LIM),DE
    LD   A,(TG_OBANK)
    CALL TG_LENAT
    LD   C,(HL)
    INC  HL
    LD   B,(HL)
    LD   (TG_ROCAP),BC
    LD   HL,(TG_IMAGE)
    LD   DE,RT_SIZE+3
    ADD  HL,DE
    LD   A,(TG_OBANK)
    LD   D,A
    LD   A,(TG_EBANK)
    CP   D
    JR   NZ,.ROBASE
    LD   DE,(TG_ILEN)
    ADD  HL,DE
    LD   DE,RT_VLEN+RT_SLEN
    ADD  HL,DE
    LD   DE,(AG_DLEN)
    ADD  HL,DE
.ROBASE:
    LD   (TG_ROPOS),HL
    OR   A
    RET

; Consume DE bytes from the selected bank after one provider operation.
;@ROUTINE IN DE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,HL
TG_SPEND:
    LD   HL,(EM_LIM)
    OR   A
    SBC  HL,DE
    JP   C,TG_FULL
    LD   B,H
    LD   C,L
    LD   HL,(EM_PTR)
    ADD  HL,DE
    JR   NC,.OK
    LD   A,B
    OR   C
    JP   NZ,TG_FULL
.OK:
    LD   (EM_PTR),HL
    LD   (EM_LIM),BC
    OR   A
    RET

; Ask the context-sensitive provider for one complete resolved runtime and
; consume its identity-fixed extent from the selected bank.
;@ROUTINE IN A,HL OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_LINK:
    LD   DE,RT_IDENT
    LD   BC,RT_SIZE
    LD   IX,TG_CBASE
    CALL PUB_RT
    LD   DE,RT_SIZE
TG_CLAIM:
    JP   C,TG_FAIL
    JR   TG_SPEND

; Banked output is always ROM. Initialize one retained cursor/capacity pair
; per bank, emit every uniform runtime, the entry-only startup/initial image,
; and then the declaration-ordered aggregate constants before source code.
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_OPENB:
    LD   A,(TG_LMODE)
    OR   A
    JP   Z,TG_DENY
    LD   HL,(TG_IMAGE)
    LD   DE,3
    ADD  HL,DE
    LD   (TG_RT),HL
    LD   HL,0
    LD   (TG_RO),HL
    CALL TG_SETUP
    LD   IX,(TG_DESC)
    CALL PUB_OPEN
    JP   C,TG_FAIL
    LD   A,(TG_BCNT)
    LD   B,A
    LD   HL,TG_BTAB
.INITLOOP:
    LD   DE,(TG_IMAGE)
    LD   (HL),E
    INC  HL
    LD   (HL),D
    INC  HL
    LD   DE,(TG_ICAP)
    LD   (HL),E
    INC  HL
    LD   (HL),D
    INC  HL
    DJNZ .INITLOOP
    LD   A,TG_OFF
    LD   (TG_OBANK),A
    LD   C,0
.BANKLOOP:
    LD   A,C
    PUSH BC
    CALL TG_PICK
    POP  BC
    LD   A,(TG_EBANK)
    CP   C
    JR   NZ,.EMPTY
    LD   A,$C3
    PUSH BC
    CALL TG_STUB
    POP  BC
    JR   .RUNTIME
.EMPTY:
    LD   DE,3
    PUSH BC
    CALL TG_SPEND
    POP  BC
.RUNTIME:
    PUSH BC
    LD   A,C
    LD   HL,(TG_RT)
    CALL TG_LINK
    POP  BC
    LD   A,(TG_EBANK)
    CP   C
    JR   NZ,.NEXT
    LD   HL,(EM_PTR)
    LD   DE,(TG_ILEN)
    ADD  HL,DE
    JP   C,TG_FULL
    LD   (TG_RO),HL
    CALL TG_BOOT
    LD   HL,(EM_PTR)
    CALL TG_RAM
    PUSH BC
    LD   HL,AG_DATA
    LD   BC,(AG_DLEN)
    CALL EM_BLOCK
    POP  BC
.NEXT:
    LD   A,(TG_OBANK)
    LD   C,A
    INC  C
    LD   A,(TG_BCNT)
    CP   C
    JR   NZ,.BANKLOOP
    JP   GA_PLACE

; HL is a region base and DE a nonzero capacity. Carry reports every wrapped
; end except the legal exact mathematical end $10000.
;@ROUTINE IN DE,HL OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,HL
TG_CHECK:
    LD   A,D
    OR   E
    JP   Z,TG_FULL
    ADD  HL,DE
    JR   NC,.OK
    LD   A,H
    OR   L
    JP   NZ,TG_FULL
.OK:
    OR   A
    RET

; Classify two checked nonempty regions without storing an exclusive $10000
; end in a word. Loaded means writable is wholly inside image; ROM means the
; half-open regions are disjoint. Every partial overlap is rejected.
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL
TG_CLASS:
    LD   HL,(TG_RW)
    LD   DE,(TG_IMAGE)
    OR   A
    SBC  HL,DE                     ; writable offset from image base
    JR   C,.BEFORE
    LD   DE,(TG_ICAP)
    PUSH HL
    OR   A
    SBC  HL,DE
    POP  BC                        ; BC = writable offset
    JR   NC,.ROM                   ; starts at or after image end
    LD   HL,(TG_ICAP)
    OR   A
    SBC  HL,BC                     ; remaining image capacity
    LD   DE,(TG_RCAP)
    OR   A
    SBC  HL,DE
    JP   C,TG_DENY
    XOR  A
    LD   (TG_LMODE),A
    RET
.BEFORE:
    LD   HL,(TG_IMAGE)
    LD   DE,(TG_RW)
    OR   A
    SBC  HL,DE                     ; distance to image start
    LD   DE,(TG_RCAP)
    OR   A
    SBC  HL,DE
    JP   C,TG_DENY
.ROM:
    LD   A,TG_LROM
    LD   (TG_LMODE),A
    OR   A
    RET

; Build the compiler-owned portion of the complete operating-layer link
; context. Service destinations are supplied by the adapter at this call.
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_SETUP:
    LD   HL,(TG_RT)
    LD   (TG_CRT),HL
    LD   HL,(TG_RW)
    LD   (TG_CRAM),HL
    LD   DE,(TG_RCAP)
    LD   (TG_CRCAP),DE
    LD   (TG_CVEC),HL
    LD   DE,RT_VLEN
    ADD  HL,DE
    JR   C,.FULL
    LD   (TG_CRUN),HL
    LD   DE,RT_SLEN
    ADD  HL,DE
    JR   C,.FULL
    LD   (TG_CDATA),HL
    LD   BC,(AG_DLEN)
    LD   DE,(PR_BSS)
    LD   H,B
    LD   L,C
    ADD  HL,DE
    JR   C,.FULL
    LD   (TG_CDCAP),HL
    LD   HL,(TG_CDATA)
    LD   DE,(AG_DLEN)
    ADD  HL,DE
    JR   C,.FULL
    LD   (TG_BSS),HL
    LD   A,(TG_BCNT)
    CP   1
    JR   Z,.FLAT
    LD   HL,0
    LD   (TG_CRO),HL
    LD   (TG_COCAP),HL
    JR   .RODONE
.FLAT:
    LD   HL,(TG_RO)
    LD   A,(TG_LMODE)
    OR   A
    JR   Z,.ROSET
    LD   DE,RT_VLEN+RT_SLEN
    ADD  HL,DE
    JR   C,.FULL
    LD   DE,(AG_DLEN)
    ADD  HL,DE
    JR   C,.FULL
.ROSET:
    LD   (TG_CRO),HL
    LD   HL,(AG_ROLEN)
    LD   (TG_COCAP),HL
.RODONE:
    CALL TG_SIZE
    JR   C,.FULL
    LD   DE,(PR_BSS)
    ADD  HL,DE
    JR   C,.FULL
    LD   DE,(TG_RCAP)
    OR   A
    SBC  HL,DE
    JR   C,.FITS
    JR   Z,.FITS
.FULL:
    JP   TG_FULL
.FITS:
    XOR  A
    RET

; Emit a call to one identity-fixed helper in the context-linked runtime.
; DE is the helper offset published by nucleus-runtime-identity.asmi.
;@ROUTINE IN DE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,DE,HL
EM_HELP:
    LD   HL,(TG_RT)
    ADD  HL,DE
    JP   EM_CALL

; Resolve one identity-fixed writable-state offset for generated operands.
;@ROUTINE IN DE OUT A,HL,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY
TG_VAR:
    LD   HL,(TG_CRUN)
    ADD  HL,DE
    OR   A
    RET

;@ROUTINE OUT DE,HL,CARRY CLOBBERS HALFCARRY
TG_SIZE:
    LD   HL,(AG_DLEN)
    LD   DE,RT_VLEN+RT_SLEN
    ADD  HL,DE
    RET

; A is the identity-defined RAM-vector ordinal. The generated call reaches the
; writable vector rather than an address in the compiler's proof adapter.
;@ROUTINE IN A OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,DE,HL
EM_CALLV:
    CALL TG_SLOT
    JP   EM_CALL
;@ROUTINE IN A OUT HL,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,A,DE
TG_SLOT:
    LD   E,A
    ADD  A,A
    ADD  A,E
    LD   E,A
    LD   D,0
    LD   HL,(TG_CVEC)
    ADD  HL,DE
    RET

;@ROUTINE IN A OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,B,C,DE,HL
EM_JUMPV:
    CALL TG_SLOT
    LD   A,$C3
    JP   EM_OPW

; Emit the implicit flat startup at the address already accounted for by
; TG_ILEN. The entry-slot patch is resolved before source code,
; while the main operand remains the ordinary checked forward fixup.
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL
TG_BOOT:
    LD   DE,(EM_DFIX)
    LD   HL,(EM_PTR)
    CALL EM_FIXW
    LD   A,(TG_SMODE)
    OR   A
    JR   Z,.COPY
    LD   HL,0
    CALL EM_LDHL
    CALL EM_OP
    DB   $39                       ; ADD HL,SP
    CALL EM_OP
    DB   $EB                       ; EX DE,HL
    LD   HL,(TG_RW)
    LD   DE,(TG_RCAP)
    ADD  HL,DE                     ; $0000 denotes mathematical $10000
    CALL EM_LDHL
    CALL EM_OP
    DB   $F9                       ; LD SP,HL
    CALL EM_OP
    DB   $D5                       ; PUSH DE, saved incoming SP
.COPY:
    LD   A,(TG_LMODE)
    OR   A
    JR   Z,.CLEAR
    LD   HL,(TG_RO)
    CALL EM_LDHL
    LD   DE,(TG_RW)
    CALL EM_LDDE
    CALL TG_SIZE
    CALL EM_LDBC
    CALL EM_IDIOM
    DB   EP_LDIR
.CLEAR:
    LD   HL,(PR_BSS)
    LD   A,H
    OR   L
    JR   Z,.ENTRY
    LD   HL,(TG_BSS)
    CALL EM_LDHL
    LD   HL,(PR_BSS)
    CALL EM_LDBC
    LD   DE,RT_BSS
    CALL EM_HELP
.ENTRY:
    LD   A,(TG_SMODE)
    OR   A
    LD   A,$C3                     ; JP main when inheriting SP
    JR   Z,.MAIN
    LD   A,$CD                     ; CALL main before restoring SP
.MAIN:
    CALL TG_STUB
    LD   HL,(EM_PTR)
    LD   (TG_TERM),HL
    LD   A,(TG_SMODE)
    OR   A
    JR   Z,.DISPATCH
    LD   HL,TG_OLDSP
    LD   B,3
    CALL EM_BYTES
.DISPATCH:
    LD   DE,RT_RUN-RT_BASE
    LD   C,RT_OK
    CALL TG_TEST
    LD   A,6                       ; success vector
    CALL EM_JUMPV
    LD   DE,RT_TNUM-RT_BASE
    LD   C,6                       ; unhandled trap number
    CALL TG_TEST
    LD   A,7                       ; unhandled-failure vector
    CALL EM_JUMPV
    LD   A,8                       ; trap vector
    JP   EM_JUMPV

; Append the provider-owned initialized vector/state image at its run or load
; address. The same complete context that linked the helper image selects it.
;@ROUTINE IN HL OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_RAM:
    LD   A,(TG_OBANK)
    LD   DE,RT_IDENT
    LD   BC,RT_VLEN+RT_SLEN
    LD   IX,TG_CBASE
    CALL PUB_INIT
    LD   DE,RT_VLEN+RT_SLEN
    JP   TG_CLAIM

;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_SHUT:
    LD   A,(TG_BCNT)
    CP   1
    JP   NZ,TG_SHUTB
    LD   HL,(EM_PTR)
    LD   DE,(TG_CODE)
    OR   A
    SBC  HL,DE
    LD   (TG_CLEN),HL
; Loaded output appends the initialized run image after code. ROM
; output already emitted the same bytes before source code.
    LD   A,(TG_LMODE)
    OR   A
    JR   NZ,.MAP
    LD   HL,(TG_RW)
    LD   (EM_PTR),HL
    XOR  A
    LD   (TG_OBANK),A
    CALL TG_SIZE
    LD   (EM_LIM),HL
    LD   HL,(TG_RW)
    CALL TG_RAM
    LD   HL,AG_DATA
    LD   BC,(AG_DLEN)
    CALL EM_BLOCK
.MAP:
    LD   HL,(AG_ROLEN)
    LD   (TG_MALEN),HL
    LD   A,H
    OR   L
    LD   HL,0
    JR   Z,.AGGR
    LD   HL,(TG_CRO)
.AGGR:
    LD   (TG_MAGG),HL
    LD   HL,(EM_PTR)
    LD   DE,(TG_IMAGE)
    OR   A
    SBC  HL,DE
    LD   (TG_MUSED),HL
    LD   HL,(TG_IMAGE)
    LD   (TG_MEXEC),HL
    XOR  A
    LD   (TG_MEB),A
    LD   HL,(TG_RO)
    LD   DE,(TG_ROLEN)
    LD   A,D
    OR   E
    JR   NZ,.READONLY
    LD   HL,0
.READONLY:
    LD   (TG_MRO),HL
    LD   (TG_MRLEN),DE
    LD   HL,(TG_CODE)
    LD   (TG_MCODE),HL
    LD   HL,(TG_CLEN)
    LD   (TG_MCLEN),HL
    LD   HL,(TG_RW)
    LD   (TG_MRAM),HL
    LD   (TG_MINIT),HL
    LD   (TG_MVEC),HL
    LD   HL,(TG_RCAP)
    LD   (TG_MRCAP),HL
    LD   HL,RT_VLEN
    LD   (TG_MVLEN),HL
    CALL TG_SIZE
    LD   (TG_MILEN),HL
    LD   (TG_MDLEN),HL
    LD   HL,(TG_BSS)
    LD   (TG_MBSS),HL
    LD   HL,(PR_BSS)
    LD   (TG_MBLEN),HL
    LD   HL,TG_STACK
    LD   (TG_MSLEN),HL
    XOR  A
    LD   (TG_MDB),A
    LD   HL,(TG_RW)
    LD   A,(TG_LMODE)
    OR   A
    JR   Z,.LOADAT
    LD   HL,(TG_RO)
.LOADAT:
    LD   (TG_MDATA),HL
    LD   IX,TG_MAP
    CALL PUB_FLAT
TG_CMT:
    JR   C,TG_QUIT
    CALL PUB_CMT
    JR   C,TG_QUIT
    XOR  A
    RET

; The operating adapter already owns the descriptor, part-bank array, and
; NOBJ encoder. Give it the two compact retained per-bank tables plus the
; common layout state; it deterministically forms and validates the MAP.
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_SHUTB:
    CALL TG_SAVE
    JR   C,TG_QUIT
    LD   IX,(TG_DESC)
    LD   IY,TG_BTAB
    LD   HL,TG_ROTAB
    CALL PUB_BANK
    JR   TG_CMT

;@ROUTINE IN A OUT A,CARRY,ZERO CLOBBERS SIGN,PARITY,HALFCARRY,BC,DE,HL,IX,IY
TG_ABORT:
    PUSH AF
    LD   A,(TG_OBANK)
    INC  A
    CALL NZ,PUB_UNDO
    POP  AF
    SCF
    RET

TG_DENY:
    LD   A,DG_CFG
    JR   TG_RAISE
; Fixup resolution closes the bank selector before MAP/COMMIT, while the sink
; generation remains open. Abort that late phase here; the production
; diagnostic continuation subsequently sees TG_OFF and therefore
; cannot issue a second abort.
TG_QUIT:
    PUSH AF
    CALL PUB_UNDO
    POP  AF
TG_FAIL:
    OR   A
    JR   NZ,TG_RAISE
    LD   A,DG_OUT
TG_RAISE:
    JP   DG_ISSUE

TG_OLDSP: DB   $C1,$E1,$F9         ; discard CALL return / restore SP
; JR NZ across one JP
